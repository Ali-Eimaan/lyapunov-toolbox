function solver = assert_yalmip_env(requested)
%ASSERT_YALMIP_ENV  Fail early, and actionably, on a missing YALMIP or SDP solver.
%
%   SOLVER = ASSERT_YALMIP_ENV(REQUESTED) checks that YALMIP and the requested
%   SDP solver are on the MATLAB path, and returns the resolved solver name.
%   Errors with an actionable message otherwise.
%
%   Call this at the TOP of every entry-point script, before the first SDPVAR.
%   MATLAB's own diagnostic for a missing YALMIP is
%
%       Unrecognized function or variable 'sdpvar'.
%
%   which does not tell a first-time user what to install or where to get it.
%   The whole point of this file is that nobody should have to guess.
%
%   It deliberately does NOT substitute a different solver when the requested
%   one is absent: two benchmark rows produced by different solvers without
%   saying so are worse than one missing row.
%
%   See also: COMPUTE_ROA_YALMIP, VAN_DER_POL_ROA, PENDULUM_ROA.

if nargin < 1 || isempty(requested)
    requested = 'mosek';
end

% ------------------------------------------------------------------ YALMIP
missing = {};
if isempty(which('sdpvar')),   missing{end+1} = 'sdpvar';   end
if isempty(which('solvesos')), missing{end+1} = 'solvesos'; end

if ~isempty(missing)
    error('lyapunovToolbox:noYalmip', ...
        ['YALMIP is not on the MATLAB path (missing: %s).\n\n' ...
         'The MATLAB side of lyapunov-toolbox is an independent SOS\n' ...
         'implementation used to cross-validate the Julia results; it needs\n' ...
         'YALMIP plus one SDP solver. To set it up:\n\n' ...
         '  1. Download YALMIP:   https://github.com/yalmip/YALMIP/archive/master.zip\n' ...
         '  2. Unzip it, then in MATLAB:\n' ...
         '       addpath(genpath(''<path>/YALMIP-master''))\n' ...
         '       savepath\n' ...
         '  3. Install a free SDP solver (SeDuMi; Mosek needs a licence):\n' ...
         '       https://github.com/sqlp/sedumi\n' ...
         '       addpath(genpath(''<path>/sedumi'')); savepath\n' ...
         '  4. Check it works:   yalmiptest\n\n' ...
         'Then re-run with the free solver, e.g.\n' ...
         '       van_der_pol_roa(''Solver'', ''sedumi'')\n\n' ...
         'The Julia path (julia/) needs none of this and is the primary\n' ...
         'implementation; MATLAB is optional.'], ...
        strjoin(missing, ', '));
end

% ------------------------------------------------------------------ solver
probes = struct('mosek', 'mosekopt', 'sedumi', 'sedumi', 'sdpt3', 'sdpt3');
if ~isfield(probes, requested)
    error('lyapunovToolbox:unknownSolver', ...
          'Unknown solver ''%s''; expected mosek, sedumi, or sdpt3.', requested);
end

names     = fieldnames(probes);
available = names(cellfun(@(nm) ~isempty(which(probes.(nm))), names));

if ismember(requested, available)
    solver = requested;
    return;
end

if isempty(available)
    error('lyapunovToolbox:noSdpSolver', ...
        ['YALMIP is installed but no SDP solver is on the path (looked for\n' ...
         'mosekopt, sedumi, sdpt3).\n\n' ...
         'Install SeDuMi (free):  https://github.com/sqlp/sedumi\n' ...
         '  addpath(genpath(''<path>/sedumi'')); savepath\n\n' ...
         'then re-run with   ...(''Solver'', ''sedumi'').\n\n' ...
         'This routine will not fall back to a default solver: a silently\n' ...
         'substituted solver produces a number nobody can reproduce.']);
end

error('lyapunovToolbox:solverNotFound', ...
      ['Requested solver ''%s'' is not on the path. Available: %s.\n' ...
       'Pass it explicitly, e.g. ...(''Solver'', ''%s''), rather than relying\n' ...
       'on a fallback.'], ...
      requested, strjoin(available', ', '), available{1});

end
